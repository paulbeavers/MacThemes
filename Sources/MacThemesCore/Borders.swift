import AppKit
import Foundation

/// With `borders = yes`, JankyBorders (github.com/FelixKratz/JankyBorders)
/// draws a border round every window, like lucent's Hyprland borders: the
/// focused window gets `border_active`, the rest `border_inactive`.
///
///   border_active   = mauve blue    one colour, or two for a gradient
///   border_inactive = surface0      default: lucent's `border` key, else surface0
///   border_width    = 5
///   border_style    = round | square
///
/// The settings go to ~/.config/borders/bordersrc, which JankyBorders runs at
/// start; a running instance is updated in place.
public enum Borders {
    static var configDir: URL {
        let env = ProcessInfo.processInfo.environment
        let cfg = env["XDG_CONFIG_HOME"].flatMap { $0.isEmpty ? nil : $0 } ?? (NSHomeDirectory() + "/.config")
        return URL(fileURLWithPath: cfg).appendingPathComponent("borders")
    }
    static var rcURL: URL { configDir.appendingPathComponent("bordersrc") }
    static let marker = "# Generated by MacThemes"

    public static var binary: String? {
        ["/opt/homebrew/bin/borders", "/usr/local/bin/borders"].first {
            FileManager.default.isExecutableFile(atPath: $0)
        }
    }

    public static func options(_ theme: Theme) -> [String] {
        func argb(_ c: RGB) -> String { "0xff" + c.hex }
        let activeSpec = (theme["border_active"] ?? "mauve blue")
            .split(whereSeparator: { $0 == " " || $0 == "," }).map(String.init)
        let active = activeSpec.compactMap { theme.color($0) }
        let activeArg: String
        if active.count >= 2 {
            activeArg = "gradient(top_left=\(argb(active[0])),bottom_right=\(argb(active[1])))"
        } else {
            activeArg = argb(active.first ?? theme.role("mauve"))
        }
        let inactive = theme.color(theme["border_inactive"]) ?? theme.color(theme["border"]) ?? theme.role("surface0")
        let width = theme["border_width"].flatMap(Double.init) ?? 5
        let style = theme["border_style"]?.lowercased() == "square" ? "square" : "round"
        return ["style=\(style)", "width=\(width)", "hidpi=on",
                "active_color=\(activeArg)", "inactive_color=\(argb(inactive))"]
    }

    public static func describe(_ theme: Theme) -> String {
        let a = theme["border_active"] ?? "mauve blue"
        let i = theme["border_inactive"] ?? theme["border"].map { "#\($0)" } ?? "surface0"
        return "active \(a), inactive \(i)"
    }

    public static func apply(_ theme: Theme) throws -> String {
        guard let bin = binary else {
            throw ThemeError.invalid("JankyBorders isn't installed — brew install FelixKratz/formulae/borders")
        }
        let opts = options(theme)
        try writeRC(opts)

        if System.run("/usr/bin/pgrep", ["-x", "borders"]).status == 0 {
            // A second invocation with arguments updates the running instance.
            System.run(bin, opts)
            return "updated"
        }
        // Not running: start it, under brew services when available so it
        // comes back at login.
        let brew = ["/opt/homebrew/bin/brew", "/usr/local/bin/brew"].first {
            FileManager.default.isExecutableFile(atPath: $0)
        }
        if let brew, System.run(brew, ["services", "start", "borders"]).status == 0 {
            return "started (brew services)"
        }
        let p = Process()
        p.executableURL = URL(fileURLWithPath: bin)
        p.arguments = opts
        p.standardOutput = FileHandle.nullDevice
        p.standardError = FileHandle.nullDevice
        try p.run()
        return "started"
    }

    static func writeRC(_ opts: [String]) throws {
        let fm = FileManager.default
        try fm.createDirectory(at: configDir, withIntermediateDirectories: true)
        if let old = try? String(contentsOf: rcURL, encoding: .utf8), !old.contains(marker) {
            let backup = configDir.appendingPathComponent("bordersrc.before-macthemes")
            if !fm.fileExists(atPath: backup.path) { try fm.copyItem(at: rcURL, to: backup) }
        }
        let body = """
            \(marker) — edits here are overwritten.
            # Your previous bordersrc, if any, is bordersrc.before-macthemes.
            options=(
            \(opts.map { "    \"\($0)\"" }.joined(separator: "\n"))
            )
            borders "${options[@]}"

            """
        try ("#!/bin/bash\n" + body).write(to: rcURL, atomically: true, encoding: .utf8)
        try fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: rcURL.path)
    }
}
