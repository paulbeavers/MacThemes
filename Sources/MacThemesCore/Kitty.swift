import Foundation

/// With `kitty = yes`, the palette is written to ~/.config/kitty/macthemes.conf
/// and running kitty windows are told to reload. kitty.conf is never edited:
/// add `include macthemes.conf` to it yourself, after any other colour include
/// you want this to override.
///
/// Like lucent, `terminal = <slug>` takes the palette from another theme, so a
/// light desktop can keep a dark terminal; `mono` sets the font and
/// `terminal_alpha` the background opacity.
public enum Kitty {
    public static var confURL: URL {
        let env = ProcessInfo.processInfo.environment
        let cfg = env["XDG_CONFIG_HOME"].flatMap { $0.isEmpty ? nil : $0 } ?? (NSHomeDirectory() + "/.config")
        return URL(fileURLWithPath: cfg).appendingPathComponent("kitty/macthemes.conf")
    }

    public static func render(_ theme: Theme) throws -> String {
        var p = theme
        if let other = theme["terminal"], !other.isEmpty, other != theme.slug {
            p = try Theme.load(other)
        }
        func c(_ role: String) -> String { "#" + p.role(role).hex }
        let light = p.mode == "light"
        var lines = [
            "# Generated by MacThemes from \"\(theme.name)\" — edits here are overwritten.",
            "",
            "foreground              \(c("text"))",
            "background              \(c("base"))",
            "selection_foreground    \(c("base"))",
            "selection_background    \(c("rosewater"))",
            "cursor                  \(c("rosewater"))",
            "cursor_text_color       \(c("base"))",
            "url_color               \(c("rosewater"))",
            "active_border_color     \(c("mauve"))",
            "inactive_border_color   \(c("surface1"))",
            "active_tab_foreground   \(c("crust"))",
            "active_tab_background   \(c("mauve"))",
            "inactive_tab_foreground \(c("subtext"))",
            "inactive_tab_background \(c("mantle"))",
            "tab_bar_background      \(c("crust"))",
            "",
        ]
        // Black and white assume a background, so a light palette swaps them.
        let black = light ? ("subtext", "overlay") : ("surface1", "overlay")
        let white = light ? ("surface1", "surface0") : ("subtext", "text")
        lines += ["color0  \(c(black.0))", "color8  \(c(black.1))",
                  "color7  \(c(white.0))", "color15 \(c(white.1))"]
        for (n, role) in ["red", "green", "yellow", "blue", "pink", "teal"].enumerated() {
            lines += ["color\(n + 1)  \(c(role))", "color\(n + 9) \(c(role))"]
        }
        if let mono = theme["mono"], !mono.isEmpty { lines += ["", "font_family \(mono)"] }
        if let a = theme["terminal_alpha"], !a.isEmpty { lines += ["background_opacity \(a)"] }
        return lines.joined(separator: "\n") + "\n"
    }

    public static func apply(_ theme: Theme) throws {
        let url = confURL
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try render(theme).write(to: url, atomically: true, encoding: .utf8)
        // kitty re-reads its config on SIGUSR1.
        System.run("/usr/bin/pkill", ["-USR1", "-x", "kitty"])
    }

    /// Whether kitty.conf already includes the generated file.
    public static var isIncluded: Bool {
        let main = confURL.deletingLastPathComponent().appendingPathComponent("kitty.conf")
        guard let text = try? String(contentsOf: main, encoding: .utf8) else { return false }
        return text.components(separatedBy: .newlines).contains {
            $0.trimmingCharacters(in: .whitespaces).hasPrefix("include") && $0.contains("macthemes.conf")
        }
    }
}
